/* ────────────────────────────────────────────────────────────
   VOLG JESUS — WEEK 10: "DIESELFDE SAAD. VERSKILLENDE GROND."

   Dewald het die week op 16 Oktober 2026 voluit gestuur, taalversorg. Dag 1 se
   hoofboodskap staan hier PRESIES soos hy dit gegee het: *"GEBRUIK DIE VOLGENDE
   BOODSKAP PRESIES SOOS DIT HIER STAAN. MOENIE ENIGE WOORD VERANDER NIE."* Sy
   woorde op Dag 2 tot 5 staan ook so — hy het hulle self kort geskryf.

   Dit is 'n NUWE week. Daar was geen Week 10 voor hierdie een nie (die les van
   Week 8: kyk eers — sien CLAUDE.md).

   ── GEEN STEMBOODSKAP ──

   *"Daar is GEEN stemnota of klank in Week 10 nie. Week 10 moet dieselfde werk
   as die vorige leesweke."* Dag 1 se hoofboodskap is dus 'n `boodskap`-blok,
   oop en nie toegevou nie, en `geskreweBoodskap: true` op die plat rekord.

   ── DAG 1 SE GEBED STAAN IN DIE BOODSKAP ──

   Elke ander dag sluit met 'n eie gebed-blok. Dag 1 nie: Dewald se boodskap
   EINDIG met die gebed ("Here, ondersoek my hart… Amen."), en hy het daar geen
   aparte GEBED gegee nie. Om dit uit die boodskap te haal, is om sy boodskap te
   verander; om dit te herhaal, is om dit twee keer op een blad te sit.

   ── DIE PERKE ──

   Vyf inhoudsblokke per dag en hoogstens twee skryfkassies — dit het sonder
   een samesmelting gepas:

     · Dag 1: LEES, die boodskap, die vraag;
     · Dag 2–4: LEES, die teks, die vraag (Dag 3: 'n keuse), die gebed;
     · Dag 5: LEES, die teks, KYK TERUG, JOU VOLGENDE STAP, die gebed.

   "JOU VOLGENDE STAP" is 'n TEKSBLOK: dit is 'n opdrag, nie 'n vraag nie.

   ── GEEN TERUGBLIK-BLOK OP DAG 5 NIE ──

   "KYK TERUG" verwys wel na Dag 1 se vraag, maar Dag 5 het reeds vyf blokke.
   Die mens se eie Dag 1-woorde kom steeds terug — op die klaar-skerm, deur
   WEEK10_REIS, wat by `grond1` begin.

   ── DIE AANHALINGS ──

   Al die gedeeltes is teen die egte public/gab/ nagegaan en bestaan. Twee
   plekke in Dewald se teks verskil van die GAB se bewoording, en hulle staan
   hier PRESIES soos hy hulle geskryf het:

     · "Wie ore het om te hoor, moet
        luister." (Dag 1 en Dag 2)       — GAB (Mark 4:9): "Hy wat ore het om te
                                            hoor, laat hom hoor."
     · "die bekommernisse van hierdie
        wêreld, die verleiding van
        rykdom, en die begeertes na
        ander dinge"                     — GAB (4:19): "die sorge van hierdie
                                            wêreld, en die bedrieglikheid van
                                            rykdom, en die begeerlikhede van
                                            ander dinge"

   Dieselfde besluit as Week 7 tot 9: Dewald se eie bewoording, dus 'n
   akkuraatheid-vraag en nie 'n lisensie-vraag nie. Hy is daarop gewys.

   ── DIE TWEE WALLPAPERS ──

   Dewald laai hulle self op. `wallpaperDag1` sluit Dag 1 af, `wallpaper` sluit
   die week af op Dag 5 — presies waar hy hulle gesit het.
   ──────────────────────────────────────────────────────────── */


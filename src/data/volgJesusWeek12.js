/* ────────────────────────────────────────────────────────────
   VOLG JESUS — WEEK 12: "JESUS SÊ: JULLE MOET JULLE VYANDE LIEFHÊ"

   Dewald het die week op 27 Oktober 2026 voluit gestuur. Dag 1 se boodskap
   staan hier PRESIES soos hy dit gegee het: *"Gebruik Dewald se Dag 1-boodskap
   presies soos dit hierbo staan. Moenie enige woord verander nie… of
   taalversorging daarop doen nie."* Sy woorde op Dag 2 tot 5 staan ook so.

   Dit is 'n NUWE week. Daar was geen Week 12 voor hierdie een nie (die les van
   Week 8: kyk eers — sien CLAUDE.md).

   ── GEEN STEMBOODSKAP ──

   *"Daar is GEEN stemnota, audio of klankspeler in Week 12 nie."* Dag 1 se
   hoofboodskap is dus 'n `boodskap`-blok, oop en nie toegevou nie, en
   `geskreweBoodskap: true` op die plat rekord.

   ── DAG 1 ──

   Dewald het die gedeelte (Matteus 5:43–48) direk onder die titel gesit, sonder
   'n leesreël, en die boodskap begin dadelik daarna. Die LEES-blok dra dus net
   die verwysing. Die boodskap EINDIG met die gebed ("Here, U weet wie my
   seergemaak het… Amen."), soos Week 10 en 11 s'n; daar is dus geen aparte
   gebed-blok op Dag 1 nie — dit sou dieselfde gebed twee keer op een blad sit.

   ── DIE PERKE ──

   Vyf inhoudsblokke per dag en hoogstens twee skryfkassies:

     · Dag 1: LEES, die boodskap, die vraag;
     · Dag 2–4: LEES, die teks, die vraag, die gebed;
     · Dag 5: LEES, die teks, KYK TERUG, JOU VOLGENDE STAP, die gebed.

   "JOU VOLGENDE STAP" is 'n TEKSBLOK: dit is 'n opdrag, nie 'n vraag nie.

   ── DIE AANHALINGS ──

   Al die gedeeltes is teen die egte public/gab/ nagegaan en bestaan. Dewald se
   aanhalings is sy EIE bewoording en nie die GAB s'n nie — bv. "Hê julle vyande
   lief en bid vir dié wat julle vervolg" (GAB: "Het julle vyande lief… en bid
   vir hulle wat julle smadelik behandel, en julle vervolg") en "Moenie deur die
   kwaad oorwin word nie" (GAB: "Word nie deur die kwaad oorwin nie"). Sy woorde
   staan onveranderd; hy is daarop gewys.

   ── DIE TWEE WALLPAPERS ──

   Dewald laai hulle self op. `wallpaperDag1` sluit Dag 1 af, `wallpaper` sluit
   die week af op Dag 5.
   ──────────────────────────────────────────────────────────── */


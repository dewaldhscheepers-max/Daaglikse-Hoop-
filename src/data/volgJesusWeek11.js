const DAG1_BOODSKAP = `Hulle vra vir Jesus wat die grootste gebod is.

Hy antwoord:

“Jy moet die Here jou God liefhê met jou hele hart en met jou hele siel en met jou hele verstand.”

En dan voeg Hy onmiddellik by:

“Jy moet jou naaste liefhê soos jouself.”

Jesus maak dus iets baie duidelik:

Jy kan nie jou liefde vir God losmaak van die manier waarop jy mense behandel nie.

Dit is maklik om te sê:

“Ek het God lief.”

Maar die moeiliker vraag is:

Hoe behandel ek mense wanneer ek kwaad is? Hoe praat ek wanneer ek teleurgesteld is? Wat doen ek wanneer iemand my seermaak?

Want liefde vir God is nie net iets wat jy bely nie.

Dit moet uiteindelik sigbaar word in jou lewe.

1 Johannes 4 stel dit baie sterk: as iemand sê dat hy God liefhet, maar sy broer haat, is daar ’n ernstige teenstrydigheid tussen wat hy sê en hoe hy leef.

JY KAN NIE AANHOU SÊ JY HET GOD LIEF TERWYL JY MENSE DOELBEWUS VERNIETIG NIE.

Jy kan bid en steeds mense met jou woorde afbreek.

Jy kan die Bybel lees en steeds bitterheid koester.

Jy kan God aanbid en steeds mense doelbewus sleg behandel.

Maar Jesus bring dit alles terug na liefde.

Liefde vir God.

Liefde vir mense.

Nie net wanneer mense maklik is om lief te hê nie.

Ook wanneer hulle jou irriteer, teleurstel of seermaak.

En hier is die moeilike deel:

Jou pyn gee jou nie die reg om ander mense seer te maak nie.

As iemand jou verkeerd behandel het, hoef daardie seer nie deur jou na die volgende persoon toe te vloei nie.

As jy nader aan God groei, moet iets van Sy liefde begin deurwerk in jou houding, jou woorde en jou optrede.

Daarom is die vraag vandag nie net:

“Het ek God lief?”

nie.

Die vraag is:

“KAN MENSE IETS VAN MY LIEFDE VIR GOD SIEN IN HOE EK HULLE BEHANDEL?”

Want die grootste gebod begin by God—

maar dit stop nie daar nie.

JOU VERHOUDING MET GOD WORD UITEINDELIK SIGBAAR IN HOE JY MENSE BEHANDEL.

Here, help my om U nie net met my woorde lief te hê nie, maar met my hele lewe. Wys my waar my houding, my woorde of my optrede nie U liefde weerspieël nie. Leer my om mense lief te hê op ’n manier wat wys dat ek aan U behoort. Amen.`

